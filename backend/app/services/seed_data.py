def seed_initial_participants_if_empty(force_all: bool = False) -> int:
    """Pre-seed the database with all 26 real verified people."""
    existing_count = count_participants()
    if existing_count >= 25 and not force_all:
        return existing_count

    with get_connection() as conn:
        existing_names = {row["name"] for row in conn.execute("SELECT name FROM participants").fetchall()}

    inserted = 0
    for p_data in INITIAL_PARTICIPANTS:
        if p_data["name"] in existing_names:
            continue
        try:
            participant = create_participant(p_data)
            analysis = analyze_profile(participant)
            update_participant_analysis(participant["id"], analysis)
            inserted += 1
        except Exception as e:
            print(f"Error seeding participant {p_data['name']}: {e}")

    return count_participants()
